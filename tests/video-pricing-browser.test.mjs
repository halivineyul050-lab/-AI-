import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { buildApplication } from '../server.mjs';
import { launchSandboxedBrowser } from '../backend/nestdutio/browser.mjs';

test('pricing renders, switches options, compares and exports in a browser', { timeout: 45000 }, async t => {
  const directory = mkdtempSync(join(tmpdir(), 'nikai-pricing-browser-'));
  const app = buildApplication({ dbPath: join(directory, 'test.db'), logger: false, environment: 'test' });
  let browser, cleanup = async () => {};
  t.after(async () => {
    await browser?.close(); await cleanup(); await app.close();
    rmSync(directory, { recursive: true, force: true });
  });
  const address = await app.listen(0, '127.0.0.1');
  const executable = process.platform === 'win32' ? 'C:/Program Files/Google/Chrome/Application/chrome.exe'
    : await (await import('@sparticuz/chromium')).default.executablePath();
  ({ browser, cleanup } = await launchSandboxedBrowser(executable, 20000));
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(() => { window.print = () => {}; });
  const page = await context.newPage(), errors = [], dialogs = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', async dialog => { dialogs.push(dialog.message()); await dialog.accept(); });
  assert.equal((await page.goto(`http://127.0.0.1:${address.port}/video-pricing`)).status(), 200);
  assert.ok(await page.locator('#tbody tr').count() > 1);
  assert.equal(await page.locator('#summaryGrid .summary-item').count(), 6);
  await page.locator('.tab[data-clarity="480p"]').click();
  assert.ok(await page.locator('.tab[data-clarity="480p"]').evaluate(element => element.classList.contains('active')));
  await page.locator('#rmbToggle').click();
  assert.match(await page.locator('#tbody').innerText(), /¥/);
  await page.locator('#compareBtn').click();
  assert.ok(await page.locator('#comparePanel').isVisible());
  await page.locator('button[onclick="selectAllModels(false)"]').click();
  assert.equal(await page.locator('#compareTbody tr').count(), 1);
  await page.locator('button[onclick="selectAllModels(true)"]').click();
  await page.locator('#compareDuration').selectOption('5');
  assert.ok(await page.locator('#compareTbody tr').count() > 1);
  await page.locator('.btn-export').click();
  const choices = page.locator('#exportSeriesList .exp-cb');
  assert.ok(await choices.count() > 0);
  for (const choice of await choices.all()) await choice.uncheck();
  await page.locator('.btn-gen').click();
  assert.equal(dialogs.length, 1);
  await choices.first().check();
  const opened = context.waitForEvent('page');
  await page.locator('.btn-gen').click();
  const exported = await opened;
  await exported.waitForLoadState('domcontentloaded');
  assert.ok(await exported.locator('.exp-table tbody tr').count() > 1);
  await exported.close();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`http://127.0.0.1:${address.port}/games`);
  assert.equal(await page.locator('.game-card').count(), 11);
  assert.equal(await page.locator('a.game-card[href="/games/free-city-3d"]').count(), 1);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
});
